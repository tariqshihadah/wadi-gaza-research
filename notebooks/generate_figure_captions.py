#!/usr/bin/env python
"""Generate per-folder figure caption catalogs, or check them with --check."""

from __future__ import annotations

import argparse
import ast
import calendar
import hashlib
import json
import os
import re
from collections import defaultdict
from pathlib import Path
from typing import Any
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path("docs/figure-captions.yaml")
MARKER = "<!-- Generated by generate_figure_captions.py; do not edit. -->"


def notebook_settings(path: Path, names: set[str]) -> dict[str, Any]:
    """Read caption-relevant literal settings without executing a notebook."""
    settings = {}
    notebook = json.loads(path.read_text(encoding="utf-8"))
    for cell in notebook["cells"]:
        if cell["cell_type"] != "code":
            continue
        for node in ast.parse("".join(cell["source"])).body:
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name) and target.id in names:
                        settings[target.id] = ast.literal_eval(node.value)
    if missing := names - settings.keys():
        raise ValueError(f"{path}: missing literal notebook settings: {sorted(missing)}")
    return settings


def _link(path: Path, folder: Path) -> str:
    return quote(Path(os.path.relpath(path, folder)).as_posix(), safe="/.-_")


def _span(values: list[int]) -> str:
    return f"{values[0]}-{values[-1]}"


def _context(root: Path, recipe: dict[str, Any], fields: dict[str, str],
             source: dict[str, Any]) -> dict[str, Any]:
    context: dict[str, Any] = dict(fields)
    context["site_name"] = source["sites"].get(fields.get("site"), fields.get("site"))
    if "month" in fields:
        month = int(fields["month"])
        if not 1 <= month <= 12:
            raise ValueError(f"Invalid month in figure filename: {fields['month']}")
        context["month_name"] = calendar.month_name[month]
    if "index" in fields:
        context["index_name"] = source["indices"][fields["index"]]
    if "model" in fields:
        context["model_description"] = source["models"][fields["model"]]
        context["model_method"] = source["model_methods"][fields["model"]]
        context["model_label"] = source["model_labels"][fields["model"]]
    if "run" in recipe:
        path = root / recipe["run"].format_map(context)
        run = json.loads(path.read_text(encoding="utf-8"))
        if "alpha" in run:
            context["ci"] = f"{100 * (1 - run['alpha']):g}"
        for key in ("tau", "min_n_eff"):
            if key in run:
                context[key] = f"{run[key]:g}"
        if "tau_sensitivity" in run:
            context["thresholds"] = ", ".join(f"{value:g}" for value in run["tau_sensitivity"])
        if "event_pairs" in run:
            context["affected"] = source["sites"][run["affected_site"]]
            context["event_pair"], context["persistence_pair"] = (
                _span(pair) for pair in run["event_pairs"]
            )
            context["event_years"] = ", ".join(str(pair[1]) for pair in run["event_pairs"])
            context["fill_n_eff"] = f"{run['fill_n_eff']:g}"
        if "reference_period" in run:
            context["reference"] = _span(run["reference_period"])
            context["years"] = _span(run["study_years"])
            context["near_zero"] = f"{run['near_zero_normal_mm']:g}"
    for name in recipe.get("fragments", []):
        context[name] = source["fragments"][name].format_map(context)
    return context


def generate_catalogs(root: Path = ROOT, *, check: bool = False) -> int:
    """Render current notebook figures; fail before writing on unknown figures.

    Return the number of captioned figures. In check mode, missing or changed
    catalogs raise ValueError and no files are written.
    """
    root = root.resolve()
    source = yaml.safe_load((root / SOURCE).read_text(encoding="utf-8"))
    recipes = source["figures"]
    patterns = [re.compile(recipe["pattern"]) for recipe in recipes]
    settings = {}
    for recipe in recipes:
        notebook = recipe["notebook"]
        names = set(recipe.get("select", {}).values())
        if names:
            settings.setdefault(notebook, {}).update(
                notebook_settings(root / "notebooks" / notebook, names)
            )
    grouped: dict[Path, list[str]] = defaultdict(list)
    unknown = []
    excluded = 0
    count = 0
    for figure in sorted((root / "outputs").rglob("*")):
        if not figure.is_file() or figure.suffix.lower() not in {".png", ".svg", ".pdf"}:
            continue
        relative = figure.relative_to(root / "outputs")
        if relative.parts[0] == "_archive" or "raw" in relative.parts:
            continue
        name = relative.as_posix()
        if any(re.fullmatch(pattern, name) for pattern in source["retired"]):
            excluded += 1
            continue
        matches = [(recipe, match) for recipe, pattern in zip(recipes, patterns)
                   if (match := pattern.fullmatch(name))]
        if len(matches) != 1:
            unknown.append(f"{name} ({len(matches)} caption templates)")
            continue
        recipe, match = matches[0]
        fields = match.groupdict()
        if any(str(fields[key]) != str(settings[recipe["notebook"]][setting])
               for key, setting in recipe.get("select", {}).items()):
            excluded += 1
            continue
        context = _context(root, recipe, fields, source)
        caption = recipe["caption"].format_map(context).strip()
        if not caption or len(caption.splitlines()) != 1:
            raise ValueError(f"{name}: caption must be a nonempty single line")
        explanation = recipe["explanation"].format_map(context).strip()
        title = recipe["title"].format_map(context)
        folder = figure.parent
        notebook = root / "notebooks" / recipe["notebook"]
        method = root / "docs" / "white-papers" / recipe["method"].format_map(context)
        for reference in (notebook, method):
            if not reference.is_file():
                raise FileNotFoundError(reference)
        digest = hashlib.sha256(figure.read_bytes()).hexdigest()
        image_link = _link(figure, folder)
        grouped[folder].append(
            f"## {title}\n\n"
            f"Figure: [{figure.name}]({image_link})\n\n"
            f"![{title}]({image_link})\n\n"
            f"**Caption.** {caption}\n\n"
            f"**Explanation.** {explanation}\n\n"
            f"Source: [{notebook.name}]({_link(notebook, folder)}); "
            f"[method]({_link(method, folder)}).\n\n"
            f"<!-- Figure SHA-256: {digest} -->\n"
        )
        count += 1
    if unknown:
        raise ValueError("Figures need caption templates (or explicit retirement):\n"
                         + "\n".join(unknown))
    expected = {}
    for folder, entries in grouped.items():
        expected[folder / "CAPTIONS.md"] = (
            f"{MARKER}\n\n# Figure captions\n\n"
            f"Maintained in [figure-captions.yaml]({_link(root / SOURCE, folder)}). "
            "Captions cover the current notebook selections only; other images in this "
            "folder may be retired or from a different selection. "
            "Figure numbering is assigned in the manuscript. "
            "Review captions alongside the images before publication.\n\n"
            + "\n".join(entries)
        )
    for catalog in (root / "outputs").rglob("CAPTIONS.md"):
        if "_archive" in catalog.relative_to(root / "outputs").parts:
            continue
        if catalog not in expected and catalog.read_text(encoding="utf-8").startswith(MARKER):
            expected[catalog] = (
                f"{MARKER}\n\n# Figure captions\n\n"
                "No figures in this folder match the current notebook selections.\n"
            )
    changed = [path for path, text in expected.items()
               if not path.exists() or path.read_text(encoding="utf-8") != text]
    if check and changed:
        raise ValueError("Caption catalogs are out of date; run "
                         "python notebooks/generate_figure_captions.py:\n"
                         + "\n".join(str(path.relative_to(root)) for path in changed))
    if not check:
        for path in changed:
            if path.exists() and not path.read_text(encoding="utf-8").startswith(MARKER):
                raise ValueError(f"Refusing to overwrite a manually maintained catalog: {path}")
        for path in changed:
            path.write_text(expected[path], encoding="utf-8")
    print(f"{'Checked' if check else 'Generated'} captions for {count} figures "
          f"in {len(grouped)} folders; {excluded} retired/unselected figures excluded.")
    return count


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check without writing files")
    args = parser.parse_args()
    generate_catalogs(check=args.check)


if __name__ == "__main__":
    main()
